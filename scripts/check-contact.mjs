import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import { defaultProfessionalConfig as config, getWhatsappLink } from '../src/config/professional.ts';
let source=stripTypeScriptTypes(await readFile(new URL('../src/utils/vcard.ts',import.meta.url),'utf8'));
let professional=stripTypeScriptTypes(await readFile(new URL('../src/config/professional.ts',import.meta.url),'utf8'));
const configUrl='data:text/javascript;base64,'+Buffer.from(professional).toString('base64');
source=source.replaceAll('../config/professional',configUrl);
const {generateVCard}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(config.fraseCaneta,'Direito com clareza.');
assert.ok(getWhatsappLink(config).startsWith('https://wa.me/5521999623802?'));
assert.equal(decodeURIComponent(getWhatsappLink(config).split('?text=')[1]),config.mensagemWhatsapp);
const card=generateVCard(config);
assert.ok(card.includes('FN:Antônio Andreoli'));
assert.ok(card.includes('TEL;TYPE=CELL,VOICE,PREF:+5521999623802'));
assert.ok(card.includes('OAB/RJ 064430'));
assert.ok(card.includes('ADR;TYPE=WORK:;;Rua Promotor Sá Carvalho\\, 5 - Centro;Nova Iguaçu;RJ;26216-180;Brasil'));
assert.ok(!generateVCard({...config,endereco:undefined}).includes('ADR;'));
assert.ok(card.startsWith('BEGIN:VCARD\r\nVERSION:3.0\r\n'));
assert.ok(card.endsWith('END:VCARD'));
assert.ok(!card.includes('URL:')&&!card.includes('EMAIL:'));
assert.equal(generateVCard({...config,whatsappE164:'',email:null}),null);
console.log('PASS: confirmed WhatsApp, encoded message, vCard name/OAB/phone, CRLF, missing channels.');
